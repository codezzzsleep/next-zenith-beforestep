"""Bounded new runtime derivatives; original scans, Lux assets and evidence stay intact."""
from contextlib import contextmanager
from pathlib import Path
import os
import tempfile
from beforestep.visualization import textures


def directory():
    path = Path(tempfile.gettempdir()) / f'beforestep-arena-assets-{os.getpid()}'
    path.mkdir(exist_ok=True)
    return path


@contextmanager
def use():
    original = textures.CACHE
    textures.CACHE = directory()
    try: yield
    finally: textures.CACHE = original


def release_derivatives():
    # These files are new scratch derivatives generated by the frozen function,
    # reconstructible from the published scans and exact world dimensions.
    # Shared historical caches and all evidence directories are never touched.
    for path in directory().glob('*_v8ax_*.obj'):
        path.unlink()
