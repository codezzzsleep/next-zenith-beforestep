def write(path,value):
    path=Path(path);path.parent.mkdir(parents=True,exist_ok=True)
    tmp=path.with_suffix(path.suffix+'.'+uuid.uuid4().hex+'.tmp');tmp.write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n');tmp.replace(path)

def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def env_for(objects=(),angle=0,start=(-.65,0),goal=1.5):
    spec={'name':'crossing','seed':0,'start':list(start),'goal_x':3.7,'terrain':{'kind':'flat','span':4,'field_x_max':3.95},
          'objects':list(objects),'channel':{'center_y':0,'half_width':2.0},'init_perturbation':{'lateral_m':0,'yaw_rad':0},
          '_hfield_dir':str(OUT/'runtime/heightfields'),'skill_cfg':{'task':'M'}}
    e=WheelLegEnv(spec,control_hz=50,max_seconds=240,nav_base=False,tip_deg=60)
    # Initial placement only; every subsequent pose change is generated by motors.
    q=e.data.qpos.copy();q[:2]=start;q[3:7]=[np.cos(np.deg2rad(angle)/2),0,0,np.sin(np.deg2rad(angle)/2)]
    e.data.qpos[:]=q;e.data.qvel[:]=0;mujoco.mj_forward(e.model,e.data)
    return e

def box_object(h,d,width=3.0,near=0.0):
    folder=OUT/'runtime/boxes'/f'{h:.6f}-{d:.6f}-{width:.6f}-{near:.6f}'
    # Arbitrary box sizes via integer voxel ranges at exact common micrometre pitch.
    pitch=1e-6
    manifest={'coordinate_frame':'world','boxes':[[0,int(round(d/pitch))-1,0,int(round(width/pitch))-1,0,int(round(h/pitch))-1]],'grid_origin':[near,-width/2,0],'pitch_m':pitch}
    if (folder/'manifest.json').exists():
        assert json.loads((folder/'manifest.json').read_text())==manifest,'Existing box dimensions differ'
    else:write(folder/'manifest.json',manifest)
    return {'posed_dir':str(folder)}

class Record:
    def __init__(self,e,threshold_index=0):
        self.e=e;self.leg_kd=5.;self.step_t=[];self.counts=[];self.contacts=[];self.q=[];self.t=[];self.phase=[];self.failure=None;self.max_tilt=0.;self.support=[]
        m=e.model
        self.robot={g for g in range(m.ngeom) if int(m.geom_bodyid[g]) in set(range(1,18))}
        # Identify by ancestry, not a hard-coded number of model bodies.
        base=mujoco.mj_name2id(m,mujoco.mjtObj.mjOBJ_BODY,'base_link');self.robot=set()
        for g in range(m.ngeom):
            b=int(m.geom_bodyid[g])
            while b and b!=base:b=int(m.body_parentid[b])
            if b==base:self.robot.add(g)
        self.wheels=e.wheel_geoms
        self.ground={g for g in range(m.ngeom) if int(m.geom_type[g]) in (int(mujoco.mjtGeom.mjGEOM_PLANE),int(mujoco.mjtGeom.mjGEOM_HFIELD))}
        self.stones=e.obstacle_geoms
        self.threshold=e._body_geoms('obstacle'+str(threshold_index))
        self.wheel_leg={g:leg for leg in LEG for g in e._body_geoms(leg+'_wheel_link')}
        e.physics_monitor=self.monitor
    def monitor(self,e):
        counts=[0,0,0,0];supported=set();ts=float(e.data.time)
        tilt=float(e._tilt());self.max_tilt=max(tilt,self.max_tilt)
        if tilt>e.tip_deg:
            counts[3]+=1
            if self.failure is None:self.failure={'kind':'unstable','reason':'tilt','t':ts,'tilt_deg':tilt}
        for c in e.data.contact:
            a,b=int(c.geom1),int(c.geom2)
            if a not in self.robot and b not in self.robot:continue
            r,other=(a,b) if a in self.robot else (b,a)
            kind=None
            if r in self.wheels and other in self.ground:kind=0;supported.add(self.wheel_leg[r])
            elif r in self.wheels and other in self.threshold:kind=1
            elif r not in self.wheels and other in self.stones:kind=2
            elif r not in self.wheels and other in self.ground:kind=3
            elif r in self.wheels and other in self.stones:kind=1
            if kind is not None:
                counts[kind]+=1
                self.contacts.append([len(self.step_t),kind,a,b,*map(float,c.pos),float(c.dist)])
                if kind>=2 and self.failure is None:self.failure={'kind':'body_collision' if kind==2 else 'unstable','reason':'contact','t':ts,'geom_ids':[a,b],'position':c.pos.tolist()}
        self.step_t.append(ts);self.counts.append(counts);self.support.append([int(leg in supported) for leg in LEG])
        return self.failure is not None
    def frame(self,phase):
        self.t.append(float(self.e.data.time));self.q.append(self.e.data.qpos.copy());self.phase.append(phase)
    def command(self,targets,omega=None,phase='move',brake=None):
        self.e.step_command(joint_targets_rad=targets,wheel_omega_rad_s=omega,wheel_brake=brake,wheel_mode='brake' if omega is None else None,kd=self.leg_kd)
        self.frame(phase)
        return self.failure is None and not self.e.truncated and not (self.e.terminated and self.e.last_termination.get('reason')!='success')
    def save(self,folder):
        folder=Path(folder);folder.mkdir(parents=True,exist_ok=True)
        np.savez_compressed(folder/'trajectory.npz',t=np.array(self.t),qpos=np.array(self.q),phase=np.array(self.phase))
        np.savez_compressed(folder/'contacts.npz',t=np.array(self.step_t),counts=np.array(self.counts,dtype=np.uint8),contacts=np.array(self.contacts).reshape(-1,8),support=np.array(self.support,dtype=np.uint8))
    def summary(self):
        a=np.array(self.counts)
        return {'physics_steps':len(a),'contact_counts':dict(zip(['wheel_ground','wheel_threshold','body_stone','unstable'],a.sum(0).astype(int).tolist())) if len(a) else {},'steps_with_wheel_stone':int((a[:,1]>0).sum()) if len(a) else 0,'max_tilt_deg':self.max_tilt,'failure':self.failure}

def joint_pose(e):return np.array([[e.data.qpos[e.J[f'{leg}_{part}_joint']['qadr']] for part in ['hip','thigh','calf']] for leg in LEG])

def stance_array(pose):return np.array([[pose[p] for p in ['hip','thigh','calf']] for leg in LEG])

def transition(rec,targets,seconds=2.0,phase='stance'):
    initial=joint_pose(rec.e);n=int(seconds*rec.e.control_hz)
    for i in range(n):
        u=(i+1)/n;s=u*u*(3-2*u)
        if not rec.command(initial+(np.array(targets)-initial)*s,phase=phase):return False
    return True

def wheel_positions(e):
    return np.array([e.data.geom_xpos[min(e._body_geoms(leg+'_wheel_link'))].copy() for leg in LEG])

def drive(rec,pose,goal_x,speed=.12,phase='drive',heading=0.,timeout=40.):
    start=rec.e.t
    while rec.e.t-start<timeout:
        e=rec.e
        if min(wheel_positions(e)[:,0])>=goal_x:return True
        q=e.data.qpos;w,x,y,z=q[3:7];yaw=np.arctan2(2*(w*z+x*y),1-2*(y*y+z*z))
        desired=float(np.clip(.8*(heading-yaw)-.6*q[1],-.20,.20));v=min(speed,.03+max(0,e.t-start)*.08)
        omega=np.array([(v+(-1 if leg in ['FL','RL'] else 1)*desired*.192)/WHEEL_R for leg in LEG]);omega=np.clip(omega,-.15/WHEEL_R,.15/WHEEL_R)
        if not rec.command(pose,omega,phase):return False
    return False
