"""Build a small Pages delivery from canonical, byte-identical repository assets.

Original main files are read-only. Generated references target a fixed commit;
only equivalent Pages copies enter the offload list. Git mutation is a separate
explicit deployment step.
"""
from pathlib import Path
import argparse, subprocess, json, hashlib, re, posixpath, urllib.parse

class Blobs:
    def __init__(self, repo):
        self.p = subprocess.Popen(['git', 'cat-file', '--batch'], cwd=repo,
                                  stdin=subprocess.PIPE, stdout=subprocess.PIPE)
        self.cache = {}
    def read(self, oid, content=False):
        if not content and oid in self.cache:
            return self.cache[oid]
        self.p.stdin.write((oid+'\n').encode()); self.p.stdin.flush()
        header = self.p.stdout.readline().decode().split(); size = int(header[2])
        h = hashlib.sha256(); chunks = []; remaining = size
        while remaining:
            data = self.p.stdout.read(min(1024*1024, remaining)); remaining -= len(data)
            h.update(data)
            if content: chunks.append(data)
        assert self.p.stdout.read(1) == b'\n'
        result = (size, h.hexdigest(), b''.join(chunks) if content else None)
        self.cache[oid] = (size, h.hexdigest(), None)
        return result
    def close(self):
        self.p.stdin.close(); self.p.wait()

def tree(repo, commit):
    out = {}
    for line in subprocess.check_output(['git', 'ls-tree', '-rl', commit], cwd=repo).decode().splitlines():
        meta, path = line.split('\t'); parts = meta.split()
        if parts[1] == 'blob': out[path] = {'oid': parts[2], 'bytes': int(parts[3])}
    return out

def build(repo, source_commit, pages_commit, output):
    source, pages = tree(repo, source_commit), tree(repo, pages_commit)
    blobs = Blobs(repo); aliases = {}; retained = {}; mismatch = []
    for path, row in pages.items():
        if not path.startswith(('assets/', 'evidence/')) or path not in source: continue
        original = source[path]; mode = 0; sha = None
        if original['oid'] == row['oid']:
            size, sha, _ = blobs.read(row['oid'])
        elif original['bytes'] < 250:
            _, _, pointer = blobs.read(original['oid'], True)
            if pointer.startswith(b'version https://git-lfs.github.com/spec/v1\n'):
                expected = re.search(rb'oid sha256:([a-f0-9]{64})', pointer).group(1).decode()
                expected_size = int(re.search(rb'\nsize (\d+)', pointer).group(1))
                size, sha, _ = blobs.read(row['oid'])
                if expected == sha and expected_size == size: mode = 1
                else: mismatch.append(path); continue
            else: continue
        else: continue
        aliases[path] = mode
        retained[path] = {'source': path, 'sha256': sha, 'bytes': row['bytes'], 'lfs': bool(mode)}
    raw = f'https://raw.githubusercontent.com/codezzzsleep/next-zenith-beforestep/{source_commit}/'
    media = f'https://media.githubusercontent.com/media/codezzzsleep/next-zenith-beforestep/{source_commit}/'
    def resolve(value, file):
        if not value or urllib.parse.urlsplit(value).scheme or value.startswith('//'): return value
        split = urllib.parse.urlsplit(value)
        path = posixpath.normpath(posixpath.join(posixpath.dirname(file), urllib.parse.unquote(split.path)))
        if path not in aliases: return value
        result = (media if aliases[path] else raw) + urllib.parse.quote(path, safe='/')
        return result + ('?'+split.query if split.query else '') + ('#'+split.fragment if split.fragment else '')
    output.mkdir(parents=True, exist_ok=True)
    changed = []
    # Static markup is rewritten before parsing can initiate old resource requests.
    attr = re.compile(r'(?P<a>\b(?:src|href|poster|data-source)=)(?P<q>["\'])(?P<u>[^"\']*)(?P=q)')
    for path, row in pages.items():
        if path in aliases or not path.endswith('.html'): continue
        _, _, body = blobs.read(row['oid'], True)
        text = body.decode('utf-8')
        new = attr.sub(lambda m: m['a']+m['q']+resolve(m['u'], path)+m['q'], text)
        if '<head' in new.lower():
            script_path = posixpath.relpath('asset-links.js', posixpath.dirname(path) or '.')
            new = re.sub(r'(<head\b[^>]*>)', lambda m: m[0]+f'<script src="{script_path}?v=assets-1"></script>', new, count=1, flags=re.I)
        if new != text:
            dest=output/path; dest.parent.mkdir(parents=True, exist_ok=True); dest.write_text(new); changed.append(path)
    # Dynamically assembled fetch, image and download URLs receive the same mapping.
    js = """/* Fixed-commit original assets; generated by offload_pages_assets.py. */
+(() => {
+ const paths = __PATHS__, raw = __RAW__, media = __MEDIA__;
+ const root = new URL('.', document.currentScript.src);
+ function resolve(value) {
+  if (typeof value !== 'string' || !value) return value;
+  let u; try { u = new URL(value, document.baseURI); } catch { return value; }
+  if (u.origin !== root.origin || !u.pathname.startsWith(root.pathname)) return value;
+  const path = decodeURIComponent(u.pathname.slice(root.pathname.length));
+  if (!Object.prototype.hasOwnProperty.call(paths, path)) return value;
+  return (paths[path] ? media : raw) + path.split('/').map(encodeURIComponent).join('/') + u.search + u.hash;
+ }
+ const fetchOriginal = window.fetch.bind(window);
+ window.fetch = (input, init) => {
+  if (input instanceof Request) { const url = resolve(input.url); return fetchOriginal(url === input.url ? input : new Request(url, input), init); }
+  return fetchOriginal(resolve(input), init);
+ };
+ const openOriginal = XMLHttpRequest.prototype.open;
+ XMLHttpRequest.prototype.open = function(method, url, ...rest) { return openOriginal.call(this, method, resolve(url), ...rest); };
+ for (const [proto, name] of [[HTMLImageElement.prototype,'src'],[HTMLMediaElement.prototype,'src'],[HTMLSourceElement.prototype,'src'],[HTMLAnchorElement.prototype,'href']]) {
+  const descriptor = Object.getOwnPropertyDescriptor(proto, name);
+  if (descriptor?.set) Object.defineProperty(proto, name, {...descriptor, set(value) { descriptor.set.call(this, resolve(value)); }});
+ }
+ const setOriginal = Element.prototype.setAttribute;
+ Element.prototype.setAttribute = function(name, value) { return setOriginal.call(this, name, /^(src|href|poster|data-source)$/i.test(name) ? resolve(value) : value); };
+ window.BeforeStepAssets = Object.freeze({resolve, sourceCommit: __COMMIT__});
+})();
""".replace('\n+', '\n')
    js = js.replace('__PATHS__',json.dumps(aliases,separators=(',',':'))).replace('__RAW__',json.dumps(raw)).replace('__MEDIA__',json.dumps(media)).replace('__COMMIT__',json.dumps(source_commit))
    (output/'asset-links.js').write_text(js); changed.append('asset-links.js')
    (output/'404.html').write_text('<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><title>原始项目素材 · BeforeStep</title><script src="/next-zenith-beforestep/asset-links.js?v=assets-1"></script></head><body><h1>查看原始项目素材</h1><p>正在打开主仓库保留的同版本原件。</p><a href="/next-zenith-beforestep/">返回 BeforeStep</a><script>const target=BeforeStepAssets.resolve(location.href);if(target!==location.href)location.replace(target);else document.querySelector("p").textContent="这个链接暂时没有找到，可返回作品首页。";</script></body></html>')
    changed.append('404.html')
    (output/'offloaded-paths.txt').write_text('\n'.join(sorted(aliases))+'\n')
    removed = sum(pages[p]['bytes'] for p in aliases)
    remaining = sum(v['bytes'] for p,v in pages.items() if p not in aliases)
    report = {'source_commit':source_commit,'pages_commit':pages_commit,'offloaded':retained,'offloaded_bytes':removed,'remaining_original_bytes':remaining,'generated_files':changed,'mismatches_preserved':mismatch,'original_main_files_modified':False}
    (output/'delivery.json').write_text(json.dumps(report,indent=2)+'\n');blobs.close()
    print(json.dumps({'offloaded':len(aliases),'offloaded_bytes':removed,'remaining_original_bytes':remaining,'generated_files':len(changed),'mismatches_preserved':len(mismatch)}),flush=True)

if __name__ == '__main__':
    p=argparse.ArgumentParser();p.add_argument('--repo',type=Path,required=True);p.add_argument('--source-commit',required=True);p.add_argument('--pages-commit',required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args();build(a.repo,a.source_commit,a.pages_commit,a.output)
